def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--events", default="../data/events_v2.csv")
    ap.add_argument("--out", default="../pine/premarket_fade.pine")
    a = ap.parse_args()

    if not os.path.exists(a.events):
        sys.exit(f"  no event table at {a.events}")
    d = load(a.events)
    for k in ("CPI", "NFP", "CLAIMS"):
        d.setdefault(k, [])
    #: a release list that came back empty would emit a strategy that
    #: never trades and reports a clean zero -- the worst failure mode
    #: a backtest has. Refuse instead.
    if len(d["CPI"]) < 100 or len(d["NFP"]) < 100:
        sys.exit(f"  REFUSED: CPI {len(d['CPI'])} NFP {len(d['NFP'])} "
                 f"-- too few to be the real table")

    src = TEMPLATE.format(
        gv=VERSION, cost=f"{COST_BP:.2f}", half_cost=f"{COST_BP / 2 / 100:.5f}",
        slot_h=SLOT_H, slot_m=SLOT_M, hold=HOLD_BARS,
        n_cpi=len(d["CPI"]), n_nfp=len(d["NFP"]), n_clm=len(d["CLAIMS"]),
        s_cpi=pine_str(d["CPI"]), s_nfp=pine_str(d["NFP"]),
        s_clm=pine_str(d["CLAIMS"]))

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write(src)
    print(f"make_pine.py v{VERSION}\n")
    print(f"  CPI {len(d['CPI'])}   NFP {len(d['NFP'])}   "
          f"CLAIMS {len(d['CLAIMS'])}   from {a.events}")
    print(f"  {len(src):,} characters written to {a.out}")
    print(f"\n  The dates come from the table, not from memory. The Pine")
    print(f"  script recomputes gross bp on TradingView's own feed and")
    print(f"  prints it beside the Python figure -- if they disagree, one")
    print(f"  of the two is wrong and the table says so on screen.")


if __name__ == "__main__":
    main()
